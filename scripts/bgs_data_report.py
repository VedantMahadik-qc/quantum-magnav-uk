"""Summarise the downloaded BGS aeromag points: survey areas, flight heights, sampling.

Reads data/raw/bgs_aeromag.csv (from fetch_bgs_aeromag.py) and writes

    docs/data-report.md      summary statistics only (safe to commit)
    data/figures/*.png       quick-look maps of the points (local only)

    uv run scripts/bgs_data_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from bgs_common import ROOT, line_key, load_points


def md_table(df: pd.DataFrame) -> str:
    """Render a DataFrame as a GitHub markdown table (avoids the optional `tabulate` dep)."""
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def altitude_reference(s: pd.DataFrame) -> str:
    """Draped (constant clearance above ground) or barometric (constant height above datum)."""
    if s.mtc.nunique() == 1:
        return f"draped, {s.mtc.iloc[0]} m clearance"
    if s.aod.nunique() == 1:
        return f"constant {s.aod.iloc[0]} m above OD"
    return "mixed"


def survey_table(d: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for area, s in d.groupby("survey_area"):
        rows.append(
            {
                "survey": area,
                "points": len(s),
                "lines": s.pipe(line_key).nunique(),
                "median E, N (km)": f"{s.grid_east.median() / 1e3:.0f}, {s.grid_north.median() / 1e3:.0f}",
                "flight height": altitude_reference(s),
                "clearance 5–95% (m)": f"{s.mtc.quantile(0.05):.0f}–{s.mtc.quantile(0.95):.0f}",
            }
        )
    return pd.DataFrame(rows)


def along_line_steps(d: pd.DataFrame) -> tuple[pd.Series, pd.Series]:
    """Distance and |field change| between consecutive points on the same line."""
    d = d.sort_values(["survey_area", "LINE_NUMB-SEG", "order_by"])
    g = d.groupby(line_key(d))
    step = np.hypot(g.grid_east.diff(), g.grid_north.diff()).dropna()
    dfield = g.mag_igrf90.diff().abs().dropna()
    return step, dfield


def quick_look(d: pd.DataFrame, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(12, 9), constrained_layout=True)
    sub = d.sample(min(len(d), 200_000), random_state=0)
    sc = axes[0].scatter(sub.grid_east / 1e3, sub.grid_north / 1e3, c=sub.mag_igrf90,
                         s=0.3, cmap="RdBu_r", vmin=-300, vmax=300, rasterized=True)
    fig.colorbar(sc, ax=axes[0], label="anomaly (nT), clipped at ±300")
    sc = axes[1].scatter(sub.grid_east / 1e3, sub.grid_north / 1e3, c=sub.mtc,
                         s=0.3, cmap="viridis", rasterized=True)
    fig.colorbar(sc, ax=axes[1], label="terrain clearance (m)")
    for ax, title in zip(axes, ["BGS aeromag anomaly", "Terrain clearance"]):
        ax.set(aspect="equal", xlabel="Easting (km)", ylabel="Northing (km)", title=title)
    fig.savefig(out_dir / "bgs_points.png", dpi=150)
    plt.close(fig)


def main() -> None:
    d = load_points()
    manifest = json.loads((ROOT / "data" / "raw" / "manifest.json").read_text())
    step, dfield = along_line_steps(d)
    q = [0.05, 0.25, 0.5, 0.75, 0.95]
    anomaly_q = d.mag_igrf90.quantile([0.001, 0.01, 0.5, 0.99, 0.999])

    report = f"""# BGS aeromagnetic data report

Generated by `scripts/bgs_data_report.py` from the download of {manifest['downloaded_utc']}
({manifest['rows']} points, sha256 `{manifest['sha256'][:12]}…`). Summary statistics only:
the raw points are fetched by script, not committed. Licence: OGL v3, "Contains British Geological Survey data © UKRI".

## Survey areas and flight heights

`mtc` = mean terrain clearance, `aod` = altitude above Ordnance Datum. `aod == ground_elev + mtc`
for {100 * (d.aod == d.ground_elev + d.mtc).mean():.2f}% of points.

{md_table(survey_table(d))}

Finding: the {d.mtc.nunique()} distinct clearance values are not noise. Three surveys in
southern and eastern England were flown at a **constant barometric height** (549 m or 457 m
above OD), so their clearance follows the terrain. Every other survey, including all of
Scotland, was draped at a constant 152 m or 305 m clearance. The map is therefore a patchwork
of observation surfaces. Upward continuation (Phase 2b) has to start from each point's real
height (`aod`), not a single nominal altitude.

## Anomaly values (`mag_igrf90`, nT)

| statistic | value |
|---|---|
| min / max | {d.mag_igrf90.min()} / {d.mag_igrf90.max()} |
| 0.1% / 1% / median / 99% / 99.9% | {' / '.join(f'{v:.0f}' for v in anomaly_q)} |
| standard deviation | {d.mag_igrf90.std():.0f} |

Values are integers (nT): the data are flight-line/contour intercepts read off maps
contoured at 10 nT.

## Sampling along flight lines

{line_key(d).nunique()} line segments, median {line_key(d).value_counts().median():.0f} points each.
Line names starting `FL` are flight lines and `T` are tie lines.

| quantile | 5% | 25% | 50% | 75% | 95% |
|---|---|---|---|---|---|
| distance between consecutive points (m) | {' | '.join(f'{v:.0f}' for v in step.quantile(q))} |
| \\|field change\\| between consecutive points (nT) | {' | '.join(f'{v:.0f}' for v in dfield.quantile(q))} |

Points are where a flight line crosses a contour, so they are dense where the field changes
quickly and sparse where it is flat. A long gap between points means the field changed by less
than one 10 nT contour interval over that distance. Across lines, the spacing is the 2 km
line spacing. Undersampling between lines, not along them, is the main source of map error.
"""
    out = ROOT / "docs" / "data-report.md"
    out.write_text(report, encoding="utf-8")
    quick_look(d, ROOT / "data" / "figures")
    print(f"wrote {out} and data/figures/bgs_points.png")


if __name__ == "__main__":
    main()
