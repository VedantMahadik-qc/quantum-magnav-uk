"""Empirical map error: grid the BGS points without 10% of flight lines, predict those lines.

Each fold holds out a random 10% of whole lines (all segments of a line go together, so
neighbouring segments cannot leak along-line information), grids the rest exactly as
grid_bgs.py does, and compares the grid with the held-out points.

Pass criteria (fixed before the first run):
  * training RMS <= 10 nT (the grid represents the data it was built from);
  * held-out RMS > training RMS (otherwise training and test data overlap).
The held-out error itself is a measurement, not pass/fail.

Writes docs/map-validation.md (summary statistics only).

    uv run scripts/holdout_bgs.py [--spacing 250] [--folds 3]
"""

from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from bgs_common import ROOT, load_points
from grid_bgs import grid_region, make_grid

HOLDOUT_FRACTION = 0.10


def whole_line_key(d: pd.DataFrame) -> pd.Series:
    """`FL-16-5` is line FL-16, segment 5: drop the segment so whole lines are held out."""
    return d.survey_area + "|" + d["LINE_NUMB-SEG"].str.rsplit("-", n=1).str[0]


def stats(r: np.ndarray) -> dict[str, float]:
    a = np.abs(r)
    return {"n": r.size, "RMS": np.sqrt(np.mean(r**2)), "median |r|": np.median(a),
            "95% |r|": np.quantile(a, 0.95)}


def run_fold(d: pd.DataFrame, lines: np.ndarray, seed: int, spacing: float,
             region: tuple[float, float, float, float]) -> tuple[dict, dict, pd.DataFrame]:
    rng = np.random.default_rng(seed)
    test_lines = rng.choice(lines, size=int(HOLDOUT_FRACTION * len(lines)), replace=False)
    is_test = whole_line_key(d).isin(test_lines).to_numpy()
    train, test = d[~is_test], d[is_test]

    grid = make_grid(train, spacing, mask_m=2_000.0, region=region)
    r_train = grid.bilinear(train.grid_east.to_numpy(float), train.grid_north.to_numpy(float))
    r_train = (r_train - train.mag_igrf90.to_numpy())
    r_test = grid.bilinear(test.grid_east.to_numpy(float), test.grid_north.to_numpy(float))
    r_test = r_test - test.mag_igrf90.to_numpy()

    covered = ~np.isnan(r_test)
    per_survey = (
        pd.DataFrame({"survey": test.survey_area.to_numpy()[covered], "r": r_test[covered]})
        .groupby("survey").r.apply(lambda r: pd.Series(stats(r.to_numpy()))).unstack()
    )
    s_test = stats(r_test[covered])
    s_test["uncovered"] = 1 - covered.mean()
    return stats(r_train[~np.isnan(r_train)]), s_test, per_survey


def fmt(v: float) -> str:
    return f"{v:.0f}" if abs(v) >= 100 else f"{v:.1f}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--spacing", type=float, default=250.0)
    parser.add_argument("--folds", type=int, default=3)
    args = parser.parse_args()

    d = load_points()
    lines = whole_line_key(d).unique()
    region = grid_region(d, args.spacing)

    rows, per_survey_all, ok = [], [], True
    for seed in range(args.folds):
        s_train, s_test, per_survey = run_fold(d, lines, seed, args.spacing, region)
        passed = s_train["RMS"] <= 10.0 and s_test["RMS"] > s_train["RMS"]
        ok &= passed
        rows.append({"fold (seed)": seed, "train RMS": s_train["RMS"], "held-out n": s_test["n"],
                     "held-out RMS": s_test["RMS"], "held-out median |r|": s_test["median |r|"],
                     "held-out 95% |r|": s_test["95% |r|"],
                     "held-out >2 km from data": f"{s_test['uncovered']:.1%}",
                     "criteria": "pass" if passed else "FAIL"})
        per_survey_all.append(per_survey)
        print(f"fold {seed}: train RMS {s_train['RMS']:.1f}, held-out RMS {s_test['RMS']:.1f}, "
              f"median {s_test['median |r|']:.1f}, 95% {s_test['95% |r|']:.1f} nT -> "
              f"{'pass' if passed else 'FAIL'}")

    folds = pd.DataFrame(rows)
    per_survey = pd.concat(per_survey_all).groupby(level=0).mean()

    def table(df: pd.DataFrame) -> str:
        cols = list(df.columns)
        out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for row in df.itertuples(index=False):
            out.append("| " + " | ".join(fmt(v) if isinstance(v, float) else str(v)
                                         for v in row) + " |")
        return "\n".join(out)

    per_survey = per_survey.reset_index().rename(columns={"index": "survey"})
    per_survey["n"] = per_survey["n"].round().astype(int)
    doc = f"""# Map validation: flight-line hold-out

Generated by `scripts/holdout_bgs.py`. For each fold, {HOLDOUT_FRACTION:.0%} of whole flight
and tie lines ({int(HOLDOUT_FRACTION * len(lines))} of {len(lines)}) are removed. The rest are
gridded exactly as in `scripts/grid_bgs.py` ({args.spacing:.0f} m, block median +
Clough–Tocher cubic), and the grid is compared with the removed points. Residual r = grid − data (nT).

Pass criteria, fixed before the first run: training RMS ≤ 10 nT and held-out RMS > training RMS.
**Overall: {'pass' if ok else 'FAIL'}.**

{table(folds)}

Held-out residuals per survey, averaged over folds:

{table(per_survey)}

## How to read this

- This measures how well the map predicts the field **between** survey lines, where it
  has to interpolate. That is the map error the navigation filter actually sees.
- **The all-GB numbers are weighted by point count**, and points are contour crossings,
  so they are densest where the field is steepest. The overall RMS is therefore dominated by
  the high-gradient Scottish surveys. The per-survey table is the fairer comparison.
- Held-out points more than 2 km from any training point fall in the NaN mask. They are
  excluded and counted in the ">2 km from data" column.
- **It overestimates the error at the real line spacing.** Removing a line doubles the local
  spacing to about 4 km, so the true map error between 2 km lines is smaller than this.
- The data themselves are only good to about one 10 nT contour interval
  (σ ≈ 10/√12 ≈ 2.9 nT if the error is uniform within an interval; my assumption), and the
  surveys are at different observation heights (see `data-report.md`).
- Comparison, written down before running: calibration error is ~5 nT achievable and
  25 nT conservative (Sengupta 2025). A map error well above 25 nT would make the map, not
  the sensor or calibration, the limit on accuracy.
"""
    out = ROOT / "docs" / "map-validation.md"
    out.write_text(doc, encoding="utf-8")
    print(f"wrote {out}; overall {'PASS' if ok else 'FAIL'}")


if __name__ == "__main__":
    main()
